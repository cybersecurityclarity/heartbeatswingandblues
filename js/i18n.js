/* ── Apply translations ─────────────────────────────────────── */
function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      // Use innerHTML to allow simple formatting; treat \n as <br>
      el.innerHTML = t[key].replace(/\n/g, '<br>');
    }
  });

  // Update <html lang> attribute
  document.documentElement.lang = lang;

  // Save to localStorage
  try { localStorage.setItem('hb-lang', lang); } catch(e) {}
}

/* ── Language selector UI ───────────────────────────────────── */
document.addEventListener('DOMContentLoaded', () => {

  const toggle    = document.getElementById('lang-toggle');
  const selector  = document.getElementById('lang-selector');
  const dropdown  = document.getElementById('lang-dropdown');
  const currentFlag = document.getElementById('current-flag');

  const flagMap = { en: '🇬🇧', th: '🇹🇭', ko: '🇰🇷', zh: '🇨🇳' };

  // Toggle dropdown
  toggle.addEventListener('click', (e) => {
    e.stopPropagation();
    selector.classList.toggle('open');
    toggle.setAttribute('aria-expanded', selector.classList.contains('open'));
  });

  // Close on outside click
  document.addEventListener('click', () => {
    selector.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
  });

  dropdown.addEventListener('click', e => e.stopPropagation());

  // Language selection
  dropdown.querySelectorAll('.lang-option').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.dataset.lang;

      // Update active state
      dropdown.querySelectorAll('.lang-option').forEach(b => b.classList.remove('active'));
      btn.classList.add('active');

      // Update flag in toggle
      currentFlag.textContent = flagMap[lang] || '🌐';

      // Apply translations
      applyLang(lang);

      // Close dropdown
      selector.classList.remove('open');
      toggle.setAttribute('aria-expanded', 'false');
    });
  });

  // Restore saved language
  try {
    const saved = localStorage.getItem('hb-lang');
    if (saved && translations[saved]) {
      const btn = dropdown.querySelector(`[data-lang="${saved}"]`);
      if (btn) btn.click();
    }
  } catch(e) {}
});
